-- IBM Db2 12.1.x schema for HerbCheck on Db2. Synthetic, unreviewed reference data only.
-- Statements end with a semicolon at the end of a line (app/ingest.py splits on that).

CREATE TABLE HERBS (
  HERB_ID   INTEGER      NOT NULL PRIMARY KEY,
  NAME      VARCHAR(80)  NOT NULL UNIQUE,
  EMBEDDING VECTOR(384, FLOAT32)
);

CREATE TABLE HERB_ALIASES (
  HERB_ID INTEGER     NOT NULL,
  ALIAS   VARCHAR(80) NOT NULL,
  PRIMARY KEY (HERB_ID, ALIAS),
  FOREIGN KEY (HERB_ID) REFERENCES HERBS (HERB_ID) ON DELETE CASCADE
);

CREATE TABLE DRUG_CLASSES (
  CLASS_ID   INTEGER     NOT NULL PRIMARY KEY,
  CLASS_NAME VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE DRUGS (
  DRUG_ID   INTEGER     NOT NULL PRIMARY KEY,
  NAME      VARCHAR(80) NOT NULL UNIQUE,
  EMBEDDING VECTOR(384, FLOAT32)
);

CREATE TABLE DRUG_CLASS_MEMBERS (
  DRUG_ID  INTEGER NOT NULL,
  CLASS_ID INTEGER NOT NULL,
  PRIMARY KEY (DRUG_ID, CLASS_ID),
  FOREIGN KEY (DRUG_ID)  REFERENCES DRUGS (DRUG_ID)          ON DELETE CASCADE,
  FOREIGN KEY (CLASS_ID) REFERENCES DRUG_CLASSES (CLASS_ID)  ON DELETE CASCADE
);

CREATE TABLE INTERACTION_RULES (
  RULE_ID   INTEGER      NOT NULL PRIMARY KEY,
  HERB_ID   INTEGER      NOT NULL,
  ATTENTION VARCHAR(10)  NOT NULL CHECK (ATTENTION IN ('high', 'moderate', 'low')),
  EVIDENCE  VARCHAR(120) NOT NULL,
  SUMMARY   VARCHAR(600) NOT NULL,
  MECHANISM VARCHAR(300) NOT NULL,
  FOREIGN KEY (HERB_ID) REFERENCES HERBS (HERB_ID) ON DELETE CASCADE
);

CREATE INDEX IX_RULES_HERB ON INTERACTION_RULES (HERB_ID);

CREATE TABLE RULE_CLASSES (
  RULE_ID  INTEGER NOT NULL,
  CLASS_ID INTEGER NOT NULL,
  PRIMARY KEY (RULE_ID, CLASS_ID),
  FOREIGN KEY (RULE_ID)  REFERENCES INTERACTION_RULES (RULE_ID) ON DELETE CASCADE,
  FOREIGN KEY (CLASS_ID) REFERENCES DRUG_CLASSES (CLASS_ID)     ON DELETE CASCADE
);

-- Privacy-by-design audit trail: counts and a one-way digest only, never the raw inputs.
CREATE TABLE CHECK_LOG (
  LOG_ID        INTEGER     NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TS            TIMESTAMP   NOT NULL DEFAULT CURRENT TIMESTAMP,
  N_HERBS       SMALLINT    NOT NULL,
  N_DRUGS       SMALLINT    NOT NULL,
  N_FINDINGS    SMALLINT    NOT NULL,
  MAX_ATTENTION VARCHAR(10) NOT NULL,
  STATUS        VARCHAR(12) NOT NULL,
  DIGEST        CHAR(16)    NOT NULL
);

CREATE VIEW V_RULE_OVERVIEW AS
  SELECT H.NAME AS HERB, R.ATTENTION, R.EVIDENCE, R.SUMMARY,
         (SELECT LISTAGG(C.CLASS_NAME, ', ') WITHIN GROUP (ORDER BY C.CLASS_NAME)
            FROM RULE_CLASSES RC JOIN DRUG_CLASSES C ON C.CLASS_ID = RC.CLASS_ID
           WHERE RC.RULE_ID = R.RULE_ID) AS DRUG_CLASSES
    FROM INTERACTION_RULES R JOIN HERBS H ON H.HERB_ID = R.HERB_ID;
